-- DDL | PostgreSQL
CREATE SCHEMA commerce;
SET search_path = commerce, public;

CREATE TABLE districts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    slug text NOT NULL UNIQUE
);

CREATE TABLE customers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    email text NOT NULL UNIQUE,
    referred_by integer REFERENCES customers(id),
    CHECK (referred_by <> id)
);

CREATE TABLE categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE products (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id integer NOT NULL REFERENCES categories(id),
    sku text NOT NULL UNIQUE,
    name text NOT NULL,
    price numeric(10,2) NOT NULL CHECK (price > 0)
);

CREATE TABLE inventory (
    product_id integer PRIMARY KEY REFERENCES products(id),
    quantity integer NOT NULL CHECK (quantity >= 0),
    reorder_level integer NOT NULL DEFAULT 8 CHECK (reorder_level >= 0)
);

CREATE TABLE discounts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE CHECK (code = upper(code)),
    percent_off numeric(5,2) NOT NULL CHECK (percent_off > 0 AND percent_off <= 100),
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE orders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES customers(id),
    discount_id integer REFERENCES discounts(id),
    placed_at timestamptz NOT NULL DEFAULT current_timestamp,
    status text NOT NULL CHECK (status IN ('confirmed', 'pending', 'cancelled')),
    discount_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    CHECK (discount_id IS NOT NULL OR discount_amount = 0)
);

CREATE TABLE order_items (
    order_id integer NOT NULL REFERENCES orders(id),
    product_id integer NOT NULL REFERENCES products(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(10,2) NOT NULL CHECK (unit_price > 0),
    PRIMARY KEY (order_id, product_id)
);

CREATE TABLE payments (
    order_id integer PRIMARY KEY REFERENCES orders(id),
    amount numeric(12,2) NOT NULL CHECK (amount >= 0),
    method text NOT NULL CHECK (method IN ('card', 'wallet')),
    status text NOT NULL CHECK (status IN ('captured', 'pending', 'failed')),
    paid_at timestamptz,
    CHECK ((status = 'captured') = (paid_at IS NOT NULL))
);

CREATE TABLE deliveries (
    order_id integer PRIMARY KEY REFERENCES orders(id),
    district_id integer NOT NULL REFERENCES districts(id),
    status text NOT NULL CHECK (status IN ('queued', 'in transit', 'delivered')),
    delivered_at timestamptz,
    CHECK ((status = 'delivered') = (delivered_at IS NOT NULL))
);

CREATE INDEX orders_customer_placed_idx ON orders (customer_id, placed_at DESC);
CREATE INDEX orders_placed_idx ON orders (placed_at DESC);
CREATE INDEX customers_referrer_idx ON customers (referred_by);
CREATE INDEX order_items_product_idx ON order_items (product_id);
CREATE INDEX deliveries_district_idx ON deliveries (district_id);
CREATE INDEX orders_discount_idx ON orders (discount_id);
CREATE INDEX products_category_idx ON products (category_id);

CREATE VIEW order_summary AS
SELECT o.id, o.customer_id, c.name AS customer, o.placed_at, o.status,
       coalesce(d.code, '') AS discount_code, o.discount_amount,
       coalesce(lines.item_count, 0)::integer AS item_count,
       coalesce(lines.subtotal, 0) AS subtotal,
       coalesce(lines.subtotal, 0) - o.discount_amount AS total,
       p.status AS payment_status, p.amount AS payment_amount, p.method AS payment_method,
       dl.district_id, ds.name AS district, dl.status AS delivery_status
FROM orders o
JOIN customers c ON c.id = o.customer_id
LEFT JOIN discounts d ON d.id = o.discount_id
LEFT JOIN (
    SELECT order_id, sum(quantity) AS item_count, sum(quantity * unit_price) AS subtotal
    FROM order_items GROUP BY order_id
) lines ON lines.order_id = o.id
LEFT JOIN payments p ON p.order_id = o.id
LEFT JOIN deliveries dl ON dl.order_id = o.id
LEFT JOIN districts ds ON ds.id = dl.district_id;

CREATE VIEW paid_orders AS
SELECT id, customer_id, district_id, placed_at, payment_amount AS revenue
FROM order_summary
WHERE status = 'confirmed' AND payment_status = 'captured';

CREATE VIEW product_stock AS
SELECT p.id, p.sku, p.name AS product, c.name AS category, p.price, i.quantity, i.reorder_level
FROM products p
JOIN categories c ON c.id = p.category_id
JOIN inventory i ON i.product_id = p.id;
